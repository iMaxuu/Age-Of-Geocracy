-- Inmutabilidad del autor, la fecha y el tipo; evita convertir una noticia común en oficial.
CREATE OR REPLACE FUNCTION public.aog_news_before_update()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  IF NEW.id IS DISTINCT FROM OLD.id OR NEW.author_id IS DISTINCT FROM OLD.author_id
     OR NEW.is_official IS DISTINCT FROM OLD.is_official OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
    RAISE EXCEPTION 'No se permite cambiar el autor, ID, fecha o tipo de publicación';
  END IF;
  IF OLD.deleted_at IS NOT NULL AND NEW.deleted_at IS DISTINCT FROM OLD.deleted_at THEN
    RAISE EXCEPTION 'El artículo retirado no puede reactivarse';
  END IF;
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS aog_news_before_update_trigger ON public.aog_news_articles;
CREATE TRIGGER aog_news_before_update_trigger
  BEFORE UPDATE ON public.aog_news_articles FOR EACH ROW EXECUTE FUNCTION public.aog_news_before_update();

-- Cola privada: el editor SQL encola rutas; la Edge Function elimina los OBJETOS reales.
-- Nunca hacer DELETE directo de storage.objects: deja archivos huérfanos en Storage.
CREATE TABLE IF NOT EXISTS public.aog_news_image_cleanup_queue (
  path text PRIMARY KEY,
  queued_at timestamptz NOT NULL DEFAULT now(),
  attempts integer NOT NULL DEFAULT 0,
  last_error text
);
ALTER TABLE public.aog_news_image_cleanup_queue ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.aog_news_image_cleanup_queue FROM anon,authenticated;

-- Las imágenes se conservan exclusivamente en los 100 artículos activos más nuevos POR IDIOMA.
-- Al publicar el artículo 101 de "es", los archivos del más viejo se encolan para eliminar.
-- Sus textos y metadatos permanecen sin límite de tiempo.
CREATE OR REPLACE FUNCTION public.aog_news_images_retention()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE
  old_paths text[];
  new_paths text[];
  cutoff_date timestamptz;
  cutoff_id bigint;
BEGIN
  -- La limpieza actualiza filas y dispara este trigger otra vez: evitar recursión.
  IF pg_trigger_depth()>1 THEN RETURN NEW; END IF;
  PERFORM pg_advisory_xact_lock(23110, hashtext(NEW.language_code));
  IF TG_OP='UPDATE' THEN
    old_paths := array_remove(array_prepend(OLD.cover_path,OLD.image_paths),NULL);
    new_paths := array_remove(array_prepend(NEW.cover_path,NEW.image_paths),NULL);
    INSERT INTO public.aog_news_image_cleanup_queue(path)
      SELECT DISTINCT path FROM unnest(old_paths) AS path
      WHERE NOT (path = ANY(new_paths)) ON CONFLICT(path) DO NOTHING;
  END IF;
  -- Si el autor lo retira, inmediatamente se limpia la referencia y se encolan sus imágenes.
  IF NEW.deleted_at IS NOT NULL THEN
    INSERT INTO public.aog_news_image_cleanup_queue(path)
      SELECT DISTINCT path FROM unnest(array_remove(array_prepend(NEW.cover_path,NEW.image_paths),NULL)) AS path
      ON CONFLICT(path) DO NOTHING;
    IF NEW.cover_path IS NOT NULL OR cardinality(NEW.image_paths)>0 THEN
      UPDATE public.aog_news_articles SET cover_path=NULL,image_paths='{}'::text[] WHERE id=NEW.id;
    END IF;
    RETURN NEW;
  END IF;
  -- Encontrar el artículo número 100 usando el índice, sin ordenar TODO el historial.
  SELECT a.created_at,a.id INTO cutoff_date,cutoff_id
  FROM public.aog_news_articles AS a
  WHERE a.language_code=NEW.language_code AND a.deleted_at IS NULL
  ORDER BY a.created_at DESC,a.id DESC OFFSET 99 LIMIT 1;
  IF cutoff_id IS NOT NULL THEN
    WITH expired AS (
      SELECT a.id,a.cover_path,a.image_paths FROM public.aog_news_articles a
      WHERE a.language_code=NEW.language_code AND a.deleted_at IS NULL
        AND (a.created_at,a.id)<(cutoff_date,cutoff_id)
        AND (a.cover_path IS NOT NULL OR cardinality(a.image_paths)>0)
    ), paths AS (
      SELECT e.cover_path AS path FROM expired e WHERE e.cover_path IS NOT NULL
      UNION ALL
      SELECT unnest(e.image_paths) FROM expired e
    )
    INSERT INTO public.aog_news_image_cleanup_queue(path)
      SELECT DISTINCT path FROM paths WHERE path IS NOT NULL ON CONFLICT(path) DO NOTHING;
    UPDATE public.aog_news_articles a SET cover_path=NULL,image_paths='{}'::text[]
      WHERE a.language_code=NEW.language_code AND a.deleted_at IS NULL
        AND (a.created_at,a.id)<(cutoff_date,cutoff_id)
        AND (a.cover_path IS NOT NULL OR cardinality(a.image_paths)>0);
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS aog_news_images_retention_trigger ON public.aog_news_articles;
CREATE TRIGGER aog_news_images_retention_trigger
  AFTER INSERT OR UPDATE OF language_code,cover_path,image_paths,deleted_at
  ON public.aog_news_articles FOR EACH ROW EXECUTE FUNCTION public.aog_news_images_retention();

