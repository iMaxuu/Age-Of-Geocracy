CREATE POLICY "news_read_published" ON public.aog_news_articles FOR SELECT TO authenticated
  USING (deleted_at IS NULL OR author_id = public.aog_news_current_player_id());
CREATE POLICY "news_insert_self" ON public.aog_news_articles FOR INSERT TO authenticated
  WITH CHECK (
    author_id = public.aog_news_current_player_id() AND deleted_at IS NULL
    AND (NOT is_official OR public.aog_news_is_admin())
  );
CREATE POLICY "news_update_self" ON public.aog_news_articles FOR UPDATE TO authenticated
  USING (deleted_at IS NULL AND author_id = public.aog_news_current_player_id())
  WITH CHECK (author_id = public.aog_news_current_player_id() AND (NOT is_official OR public.aog_news_is_admin()));
