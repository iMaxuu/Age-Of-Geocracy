CREATE OR REPLACE FUNCTION public.aog_news_current_player_id()
RETURNS bigint LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT p.id FROM public.players AS p WHERE p.auth_id = auth.uid() LIMIT 1
$$;
REVOKE ALL ON FUNCTION public.aog_news_current_player_id() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.aog_news_current_player_id() TO authenticated;

CREATE OR REPLACE FUNCTION public.aog_news_is_admin()
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.aog_news_admins n
    WHERE n.player_id = public.aog_news_current_player_id()
  )
$$;
REVOKE ALL ON FUNCTION public.aog_news_is_admin() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.aog_news_is_admin() TO authenticated;

CREATE OR REPLACE FUNCTION public.aog_news_paths_valid(owner_id bigint, cover text, gallery text[])
RETURNS boolean LANGUAGE sql IMMUTABLE SET search_path = '' AS $$
  SELECT
    (cover IS NULL OR (cover LIKE (owner_id::text || '/%') AND cover ~ ('^' || owner_id::text || '/[0-9a-f-]{36}[.]webp$')))
    AND coalesce(cardinality(gallery), 0) <= 4
    AND NOT EXISTS (
      SELECT 1 FROM unnest(gallery) AS p(path)
      WHERE p.path IS NULL OR p.path NOT LIKE (owner_id::text || '/%')
         OR p.path !~ ('^' || owner_id::text || '/[0-9a-f-]{36}[.]webp$')
    )
$$;

CREATE TABLE IF NOT EXISTS public.aog_news_articles (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  author_id bigint NOT NULL REFERENCES public.players(id) ON DELETE RESTRICT,
  language_code text NOT NULL CHECK (language_code IN ('es','en','pt','fr','de','it')),
  is_official boolean NOT NULL DEFAULT false,
  title text NOT NULL CHECK (char_length(btrim(title)) BETWEEN 4 AND 120),
  content_html text NOT NULL CHECK (char_length(content_html) BETWEEN 20 AND 30000),
  cover_path text,
  image_paths text[] NOT NULL DEFAULT '{}'::text[],
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz,
  CONSTRAINT aog_news_image_paths_check CHECK (public.aog_news_paths_valid(author_id,cover_path,image_paths))
);
CREATE INDEX IF NOT EXISTS aog_news_active_language_created_idx
  ON public.aog_news_articles (language_code,created_at DESC,id DESC) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS aog_news_official_language_idx
  ON public.aog_news_articles (language_code,is_official,created_at DESC) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS aog_news_author_idx
  ON public.aog_news_articles (author_id,created_at DESC) WHERE deleted_at IS NULL;
ALTER TABLE public.aog_news_articles ENABLE ROW LEVEL SECURITY;

